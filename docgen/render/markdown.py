"""Markdown document generation."""
from __future__ import annotations

from collections import Counter
from datetime import datetime
from typing import List

from ..model import CACHE, DATABASE, EXTERNAL, GRPC, HTTP, KAFKA, RABBITMQ, REGISTRY, STORAGE, Service
from ..workspace import Workspace
from . import mermaid

KIND_TITLE = {HTTP: "REST", GRPC: "gRPC", KAFKA: "Kafka", RABBITMQ: "RabbitMQ", DATABASE: "Database",
              CACHE: "Cache", REGISTRY: "Registry", STORAGE: "Object storage", EXTERNAL: "External"}


def md_escape(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def table(headers: List[str], rows: List[List[str]]) -> str:
    if not rows:
        return "_None detected._\n"
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(md_escape(str(c)) for c in r) + " |")
    return "\n".join(out) + "\n"


def fence(code: str) -> str:
    return f"```mermaid\n{code}\n```\n"


def tier_name(t) -> str:
    return {0: "target", 1: "direct callee"}.get(t, f"callee (depth {t})" if t is not None else "outside scope")


# ---------------------------------------------------------------------------- description
def describe(s: Service, ws: Workspace) -> str:
    """Deterministic natural-language summary assembled from extracted facts."""
    parts = []
    lang = {"java": "Java", "go": "Go"}.get(s.language, s.language)
    head = f"**{s.id}** is a {s.framework or lang} service written in {lang}"
    if s.ports.get("http"):
        head += f", listening on port {s.ports['http']}"
    if s.context_path:
        head += f" under context path `{s.context_path}`"
    parts.append(head + ".")
    ctrls = [c for c in s.components if c.kind == "controller"]
    if s.endpoints:
        areas = ", ".join(sorted({c.name.replace("Controller", "").replace("V1", "") for c in ctrls})[:12])
        parts.append(f"It exposes {len(s.endpoints)} HTTP endpoints across {len(ctrls)} "
                     f"{'controllers' if s.language == 'java' else 'route files'}" + (f" ({areas})." if areas else "."))
    sync = [d for d in s.dependencies if d.kind == HTTP]
    grpc = [d for d in s.dependencies if d.kind == GRPC]
    if sync:
        parts.append("Synchronously it calls " + ", ".join(
            f"`{d.resolved or d.target}`" for d in sync) + " over REST.")
    if grpc:
        parts.append("It uses gRPC for " + ", ".join(
            f"`{d.label.replace('gRPC: ', '')}`" for d in grpc) + ".")
    kp = [d.target for d in s.dependencies if d.kind == KAFKA and d.direction == "publish"]
    kc = [d.target for d in s.dependencies if d.kind == KAFKA and d.direction == "consume"]
    rp = [d.target for d in s.dependencies if d.kind == RABBITMQ and d.direction == "publish"]
    rc = [d.target for d in s.dependencies if d.kind == RABBITMQ and d.direction == "consume"]
    if kp or kc:
        parts.append(f"On Kafka it publishes to {len(kp)} and consumes from {len(kc)} topic(s).")
    if rp or rc:
        parts.append(f"On RabbitMQ it publishes to {len(rp)} and listens on {len(rc)} queue binding(s).")
    stores = [d for d in s.dependencies if d.kind in (DATABASE, CACHE, STORAGE)]
    if stores:
        parts.append("State is kept in " + ", ".join(d.target for d in stores) +
                     (f" ({len([e for e in s.entities if not e.startswith('redis:')])} JPA entities)" if s.entities else "") + ".")
    jobs = [c for c in s.components if c.kind == "job"]
    if jobs:
        parts.append(f"{len(jobs)} scheduled job(s) run in the background.")
    callers = sorted({e.src.split(':', 1)[1] for e in ws.edges.values()
                      if e.dst == f"svc:{s.id}" and e.src.startswith("svc:")})
    if callers:
        parts.append("Within the documented scope it is called by " + ", ".join(f"`{c}`" for c in callers) + ".")
    text = " ".join(parts)
    if s.readme_summary:
        text += f"\n\n> README: {s.readme_summary}"
    return text


# ---------------------------------------------------------------------------- index
def render_index(ws: Workspace, settings: dict) -> str:
    targets = [sid for sid, t in ws.scope.items() if t == 0]
    out = [f"# {settings.get('title') or 'Service documentation'}\n",
           f"_Generated by docgen on {datetime.now():%Y-%m-%d %H:%M} from `{settings['source_root']}` — "
           f"targets: {', '.join(f'`{t}`' for t in targets)}, depth {settings['depth']}._\n",
           "## Services in scope\n"]
    rows = []
    for sid, t in sorted(ws.scope.items(), key=lambda kv: (kv[1], kv[0])):
        s = ws.services[sid]
        rows.append([f"[{sid}](services/{sid}.md)", tier_name(t), f"{s.language} · {s.framework}",
                     s.ports.get("http", ""), s.context_path, str(len(s.endpoints)),
                     str(len([d for d in s.dependencies if d.kind in (HTTP, GRPC)])),
                     f"[{len(s.flows)} functions](features/{sid}.md)" if s.flows else "—"])
    out.append(table(["Service", "Role", "Stack", "Port", "Context path", "Endpoints", "Sync deps", "Feature diagrams"], rows))
    out.append("\n## Architecture\n")
    out.append("Container view grouped by tier. Messaging is collapsed to brokers and only the target services' "
               "data/messaging arrows are drawn; called services' stores are on their own pages. "
               "See the relationship diagram for individual topics and exchanges.\n")
    out.append(fence(mermaid.architecture(ws)))
    out.append("\n## Relationship diagram\n")
    out.append("Solid arrows are found in code; dotted arrows are inferred from configuration only. "
               "Dashed boxes are referenced services that were not found in the workspace. "
               "Shows everything touching the targets plus links between in-scope services; each called "
               "service's own external dependencies are on its page.\n")
    out.append(fence(mermaid.relationships(ws)))
    # interactions table
    out.append("\n## Interactions\n")
    rows = []
    for e in sorted(ws.edges.values(), key=lambda e: (e.kind, e.src, e.dst)):
        rows.append([ws.nodes[e.src].label, ws.nodes[e.dst].label, KIND_TITLE.get(e.kind, e.kind), e.label,
                     "inferred" if e.inferred else "code"])
    out.append(table(["From", "To", "Type", "Detail", "Source"], rows))
    # shared infra
    infra = Counter()
    for sid in ws.scope:
        for d in ws.services[sid].dependencies:
            if d.kind in (DATABASE, CACHE, REGISTRY, STORAGE, EXTERNAL):
                infra[(KIND_TITLE[d.kind], d.target)] += 1
    if infra:
        out.append("\n## Shared infrastructure\n")
        out.append(table(["Type", "Component", "Used by (#services)"], [[k, t, str(n)] for (k, t), n in sorted(infra.items())]))
    unresolved = sorted({n.label for n in ws.nodes.values() if n.type == "stub"})
    if unresolved:
        out.append("\n## Unresolved references\n")
        out.append("These names are called but no workspace project matches them. Add an entry under `aliases` "
                   "in `docgen.yaml` if they exist under a different name.\n\n" + "\n".join(f"- `{u}`" for u in unresolved) + "\n")
    return "\n".join(out)


# ---------------------------------------------------------------------------- per service
def render_service(s: Service, ws: Workspace) -> str:
    t = ws.scope.get(s.id)
    feat = f" · [features & function diagrams](../features/{s.id}.md)" if s.flows else ""
    o = [f"# {s.id}\n", f"[← index](../index.md){feat} · role: **{tier_name(t)}** · path: `{s.path}`\n",
         "## Description\n", describe(s, ws) + "\n"]
    o.append("\n## Architecture\n")
    rows = [["Language", s.language], ["Framework", s.framework], ["Version", s.version or "—"],
            ["Ports", ", ".join(f"{k}: {v}" for k, v in s.ports.items()) or "—"],
            ["Context path", s.context_path or "—"],
            ["Tech stack", ", ".join(s.tech) or "—"],
            ["Deployment", ", ".join(s.deployment) or "—"],
            ["Source files", str(s.file_count)]]
    o.append(table(["Aspect", "Value"], rows))
    if s.layers:
        o.append("\n**Code layout** (files per top-level package/folder): " +
                 ", ".join(f"`{k}` {v}" for k, v in s.layers.items()) + "\n")
    o.append("\n### Component view\n")
    o.append(fence(mermaid.service_components(s)))
    o.append("\n## Relationships\n")
    o.append(fence(mermaid.relationships(ws, focus=s.id)))

    sync = [d for d in s.dependencies if d.kind in (HTTP, GRPC)]
    if sync:
        o.append("\n### Outbound calls\n")
        for d in sync:
            tgt = f"[{d.resolved}]({d.resolved}.md)" if d.resolved and d.resolved in ws.scope else (d.resolved or d.target)
            if d.kind == GRPC and not d.resolved:
                tgt = f"{d.label.replace('gRPC: ', '')} (`{d.target}`)"
            o.append(f"\n#### {KIND_TITLE[d.kind]} → {tgt}\n")
            meta = [f"client: {d.label}"]
            if d.address:
                meta.append(f"address: `{d.address}`")
            meta += d.details
            if d.inferred:
                meta.append("target name inferred from class name")
            o.append("- " + "\n- ".join(meta) + "\n")
            if d.operations:
                rows = [[op.name, op.caller, op.matched or ("—" if not d.resolved else "not matched"),
                         str(op.evidence) if op.evidence else ""] for op in d.operations]
                o.append("\n" + table(["Operation", "Caller", "Callee handler", "Source"], rows))
    msg = [d for d in s.dependencies if d.kind in (KAFKA, RABBITMQ)]
    if msg:
        o.append("\n### Messaging\n")
        rows = []
        for d in msg:
            peers = []
            for other in ws.services.values():
                if other.id == s.id:
                    continue
                for od in other.dependencies:
                    if od.kind == d.kind and od.target == d.target and od.direction != d.direction:
                        peers.append(other.id)
            rows.append([KIND_TITLE[d.kind], d.direction, d.target, "; ".join(d.details),
                         ", ".join(sorted(set(peers))) or "—", "inferred" if d.inferred else (str(d.evidence[0]) if d.evidence else "")])
        o.append(table(["Broker", "Direction", "Topic / exchange", "Details", "Peer services", "Source"], rows))
    infra = [d for d in s.dependencies if d.kind in (DATABASE, CACHE, REGISTRY, STORAGE, EXTERNAL)]
    if infra:
        o.append("\n### Infrastructure\n")
        o.append(table(["Type", "Component", "Via", "Details"],
                       [[KIND_TITLE[d.kind], d.target, d.label, "; ".join(d.details + ([d.address] if d.address else []))] for d in infra]))

    if s.endpoints:
        o.append("\n## API endpoints\n")
        base = s.context_path.rstrip("/") if s.context_path else ""
        rows = [[e.method, base + e.path, e.component, e.handler, str(e.evidence) if e.evidence else ""]
                for e in sorted(s.endpoints, key=lambda e: (e.component, e.path))]
        o.append(table(["Method", "Path", "Component", "Handler", "Source"], rows))
    if s.provides_grpc:
        o.append("\n## gRPC services provided\n")
        o.append(table(["Service", "RPCs"], [[k, ", ".join(sorted(set(v)))] for k, v in s.provides_grpc.items()]))
    jobs = [c for c in s.components if c.kind == "job"]
    if jobs:
        o.append("\n## Scheduled jobs\n")
        o.append(table(["Job", "Schedule", "Source"], [[c.name, c.detail, str(c.evidence or "")] for c in jobs]))
    if s.entities:
        o.append("\n## Data model\n")
        o.append(", ".join(f"`{e}`" for e in s.entities) + "\n")
    if s.config_endpoints:
        o.append("\n## Configured endpoints\n")
        o.append("From application config (secrets and encrypted values removed).\n\n")
        o.append(table(["Key", "Value"], [[k, f"`{v}`"] for k, v in s.config_endpoints.items()]))
    if s.notes:
        o.append("\n## Notes\n")
        o.append("\n".join(f"- {n}" for n in s.notes) + "\n")
    if s.existing_docs:
        o.append("\n## Existing docs in the repo\n")
        o.append("\n".join(f"- `{d}`" for d in s.existing_docs) + "\n")
    return "\n".join(o)
